const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const registry = read('windows/FBS.Student.Native/PersistentManagedEnrollment.cs');
const ui = read('windows/FBS.Teacher.Launcher/TeacherPairingAuditForm.cs');
test('registry exposes read-only roster snapshot', () => assert.match(registry, /GetRosterSnapshot\(\)/));
test('snapshot refuses locked registry', () => assert.match(registry, /if \(locked\) throw new InvalidOperationException/));
test('snapshot contains identifiers and revoked list only', () => assert.match(registry, /return \(devices.Keys.OrderBy/));
test('teacher displays a read-only roster', () => assert.match(ui, /DataGridView roster = new\(\).*ReadOnly = true/s));
test('roster displays enrolled identifiers', () => assert.match(ui, /snapshot.Enrolled/));
test('roster displays revoked identifiers', () => assert.match(ui, /snapshot.Revoked/));
test('successful proof records last verified', () => assert.match(ui, /outcome.Accepted && outcome.DeviceId is not null/));
test('last verified is not presented as online status', () => assert.match(ui, /ليس اتصالًا مباشرًا/));
test('refresh button wired', () => assert.match(ui, /refreshRoster.Click/));
test('roster clears when registry is unavailable', () => assert.match(ui, /activeRegistry = null;\s*roster.Rows.Clear/));
test('roster does not expose public keys', () => assert.doesNotMatch(ui, /roster.Rows.Add\([^\n]*spki/));
test('existing listener remains identity only', () => assert.match(ui, /RunPairingAuditAsync/));
