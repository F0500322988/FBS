const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const harness = read('windows/FBS.Pairing.Integration/Program.cs');
const project = read('windows/FBS.Pairing.Integration/FBS.Pairing.Integration.csproj');
const client = read('windows/FBS.Student.Native/PinnedLanPairingClient.cs');
const server = read('windows/FBS.Teacher.Launcher/TeacherPinnedTlsListener.cs');
const studentUi = read('windows/FBS.Student.Native/StudentPairingTestForm.cs');
const teacherUi = read('windows/FBS.Teacher.Launcher/TeacherPairingAuditForm.cs');
test('M158 test executable targets Windows .NET 8', () => assert.match(project, /net8\.0-windows/));
test('M158 harness references student and teacher assemblies', () => { assert.match(project, /FBS.Student.Native.csproj/); assert.match(project, /FBS.Teacher.Launcher.csproj/); });
test('M158 generates ephemeral self-signed test certificate', () => assert.match(harness, /CreateSelfSigned/));
test('M158 certificate includes localhost DNS SAN', () => assert.match(harness, /san.AddDnsName\("localhost"\)/));
test('M158 test binds only loopback', () => assert.match(harness, /IPAddress.Loopback/));
test('M158 test enrolls explicit approved key', () => assert.match(harness, /registry.Provision\("test-student"/));
test('M158 tests approved identity', () => assert.match(harness, /registered device accepted/));
test('M158 tests wrong signing key', () => assert.match(harness, /wrong signing key rejected/));
test('M158 tests unknown device', () => assert.match(harness, /unknown device rejected/));
test('M158 tests invalid TLS pin', () => assert.match(harness, /wrong certificate fingerprint rejected/));
test('M158 test has no remote input or command execution', () => assert.doesNotMatch(harness, /SendInput|mouse_event|keybd_event|Process.Start/));
test('M158 test uses temporary registry and removes test directory', () => assert.match(harness, /Directory.Delete\(directory, recursive: true\)/));
test('M158 both UIs use matching default port', () => { assert.match(studentUi, /Value = 47443/); assert.match(teacherUi, /Value = 47443/); });
test('M158 wire protocol sends device ID first', () => assert.match(client, /SendFrameAsync\(Encoding.ASCII.GetBytes\(deviceId\)/));
test('M158 server validates ASCII ID', () => assert.match(server, /canonical ASCII/));
test('M158 client verifies 32 byte challenge', () => assert.match(client, /nonce.Length != DeviceChallengeProof.ChallengeBytes/));
test('M158 server verifies single-use proof', () => assert.match(server, /registry.VerifyOnce/));
test('M158 server closes after proof', () => assert.match(server, /Close after identity proof/));
test('M158 client requires explicit OK', () => assert.match(client, /reply\[0\] == \(byte\)'O'/));
