const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const student = fs.readFileSync(path.join(root,'windows/FBS.Student.Native/StudentPairingTestForm.cs'),'utf8');
const teacher = fs.readFileSync(path.join(root,'windows/FBS.Teacher.Launcher/TeacherPairingAuditForm.cs'),'utf8');
test('student explicit persistent mode checkbox',()=>assert.match(student,/private readonly CheckBox persistent/));
test('student uses authenticated presence client',()=>assert.match(student,/PinnedLanPairingClient\.RunPresenceAsync\(/));
test('student periodic and persistent are exclusive',()=>assert.match(student,/if \(persistent.Checked\) periodic.Checked = false/));
test('student cancellation remains visible',()=>assert.match(student,/cancel.Click \+= .*running\?\.Cancel/));
test('student does not automatically start',()=>assert.match(student,/start.Click \+=/));
test('student resets persistent control',()=>assert.match(student,/persistent.Enabled = true/));
test('teacher explicit mode selection',()=>assert.match(teacher,/private readonly CheckBox persistent/));
test('teacher selects presence listener only if opted in',()=>assert.match(teacher,/if \(persistent.Checked\)[\s\S]*listener.RunPresenceAsync/));
test('teacher retains identity-only mode',()=>assert.match(teacher,/listener.RunPairingAuditAsync/));
test('teacher heartbeat event handler',()=>assert.match(teacher,/OnPresenceHeartbeatReceived\(string deviceId, DateTimeOffset timestamp\)/));
test('teacher refreshes roster on heartbeat',()=>assert.match(teacher,/lastVerified\[deviceId\] = timestamp;\s*RefreshRoster/));
test('teacher disables mode switch during session',()=>assert.match(teacher,/persistent.Enabled = false/));
test('teacher reenables mode on stop',()=>assert.match(teacher,/persistent.Enabled = true/));
test('teacher stop cancels session',()=>assert.match(teacher,/cancellation\?\.Cancel\(\)/));
test('documentation explains limitations',()=>assert.match(fs.readFileSync(path.join(root,'M165-START-HERE.md'),'utf8'),/لا يمنح صلاحية التحكم/));
