'use strict';
const test=require('node:test');const assert=require('node:assert/strict');
const drag=require('../public/m113-seat-drag');
const base={rows:3,columns:7,seats:{'PC-01':1,'PC-02':2}};
const known=['PC-01','PC-02','PC-03'];
test('moves an assigned device into empty seat',()=>{const r=drag.move(base,'PC-01',5,known);assert.equal(r.config.seats['PC-01'],5);assert.equal(r.config.seats['PC-02'],2);});
test('swaps two explicitly assigned seats',()=>{const r=drag.move(base,'PC-01',2,known);assert.equal(r.config.seats['PC-01'],2);assert.equal(r.config.seats['PC-02'],1);});
test('displaces occupant if source has no manual seat',()=>{const r=drag.move(base,'PC-03',2,known);assert.equal(r.config.seats['PC-03'],2);assert.equal(r.config.seats['PC-02'],undefined);});
test('supports assigning previously unassigned device',()=>{const r=drag.move(base,'PC-03',3,known);assert.equal(r.config.seats['PC-03'],3);});
test('rejects unknown device',()=>assert.equal(drag.move(base,'stranger',3,known).changed,false));
test('rejects empty ID',()=>assert.equal(drag.move(base,'',3,known).changed,false));
test('rejects out of range target',()=>assert.equal(drag.move(base,'PC-01',22,known).changed,false));
test('rejects noninteger target',()=>assert.equal(drag.move(base,'PC-01',1.5,known).changed,false));
test('rejects string target',()=>assert.equal(drag.move(base,'PC-01','2',known).changed,false));
test('rejects missing known list',()=>assert.equal(drag.move(base,'PC-01',3).changed,false));
test('no-op for same seat',()=>assert.equal(drag.move(base,'PC-01',1,known).changed,false));
test('does not mutate input',()=>{drag.move(base,'PC-01',2,known);assert.deepEqual(base.seats,{'PC-01':1,'PC-02':2});});
test('preserves row and column counts',()=>{const r=drag.move(base,'PC-01',7,known);assert.equal(r.config.rows,3);assert.equal(r.config.columns,7);});
test('handles malformed configuration',()=>{const r=drag.move(null,'PC-01',1,known);assert.equal(r.config.seats['PC-01'],1);});
