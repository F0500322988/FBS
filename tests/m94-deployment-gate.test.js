'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {ITEMS,evaluate}=require('../windows/M94-Deployment-Gate');
const hash='a'.repeat(64);
const lab={stage:'M93',passed:true,expected:21,remoteInputEnabled:false};
const dist={stage:'M80',passed:true,requireInstallers:true,liveInputEnabled:false,packages:['Teacher','Student'].map(role=>({role,installer:{sha256:hash},portable:{sha256:hash}}))};
const yes=Object.fromEntries(ITEMS.map(x=>[x,true]));
test('passes complete manually confirmed evidence',()=>assert.equal(evaluate(21,lab,dist,yes).passed,true));
test('rejects capacity mismatch',()=>assert.ok(evaluate(40,lab,dist,yes).issues.includes('lab_readiness_not_verified')));
test('rejects bad capacity',()=>assert.ok(evaluate(41,lab,dist,yes).issues.includes('invalid_capacity')));
test('rejects missing M93',()=>assert.equal(evaluate(21,null,dist,yes).passed,false));
test('rejects failed M93',()=>assert.equal(evaluate(21,{...lab,passed:false},dist,yes).passed,false));
test('rejects unsigned installer gate',()=>assert.equal(evaluate(21,lab,{...dist,requireInstallers:false},yes).passed,false));
test('rejects missing installer digest',()=>assert.ok(evaluate(21,lab,{...dist,packages:dist.packages.slice(1)},yes).issues.includes('missing_package_hash_teacher')));
test('rejects remote input enabled',()=>assert.equal(evaluate(21,{...lab,remoteInputEnabled:true},dist,yes).passed,false));
test('rejects unchecked firewall',()=>assert.ok(evaluate(21,lab,dist,{...yes,udp_4181_firewall_checked:false}).issues.includes('not_confirmed_udp_4181_firewall_checked')));
test('rejects unchecked rollback',()=>assert.equal(evaluate(21,lab,dist,{...yes,uninstall_rollback_tested:false}).passed,false));
test('rejects missing approvals',()=>assert.equal(evaluate(21,lab,dist,{}).passed,false));
test('does not echo secrets into result',()=>assert.ok(!JSON.stringify(evaluate(21,lab,dist,{...yes,password:'secret'})).includes('secret')));
