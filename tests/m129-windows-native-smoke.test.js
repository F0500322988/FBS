'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');
const app = read('windows/FBS.NativeSafety.Smoke/Program.cs');
const project = read('windows/FBS.NativeSafety.Smoke/FBS.NativeSafety.Smoke.csproj');
const script = read('windows/Test-M129-Native-Safety.ps1');
test('M129 smoke is a Windows console app', () => { assert.match(project, /<OutputType>Exe<\/OutputType>/); assert.match(project, /net8\.0-windows/); });
test('M129 links real production adapter source', () => assert.match(project, /FBS.Student.Native\/WindowsInputAdapter.cs/));
test('M129 links real production startup probe', () => assert.match(project, /FBS.Student.Native\/NativeInputSafetyProbe.cs/));
test('M129 links real stop guard', () => assert.match(project, /FBS.Student.Native\/StopRaceGuard.cs/));
test('M129 links real polling guard', () => assert.match(project, /FBS.Student.Native\/PollResponseGuard.cs/));
test('M129 fails when not running on Windows', () => assert.match(app, /!OperatingSystem.IsWindows\(\)/));
test('M129 checks native input disabled', () => assert.match(app, /NativeInputSafetyProbe.VerifyDisabled\(adapter\)/));
test('M129 refuses enable request', () => assert.match(app, /!adapter.Enabled/));
test('M129 checks pointer and keyboard refusal', () => { assert.match(app, /!adapter.MovePointer/); assert.match(app, /!adapter.TapLetter/); });
test('M129 verifies stopped session rejection', () => { assert.match(app, /guard.Stop\("session-test"\)/); assert.match(app, /!guard.MayApply/); });
test('M129 verifies late response rejection', () => assert.match(app, /!PollResponseGuard.MayApply/));
test('M129 returns nonzero on failure', () => { assert.match(app, /return 1;/); assert.match(app, /return 2;/); });
test('M129 PowerShell fails when dotnet unavailable', () => assert.match(script, /Get-Command dotnet/));
test('M129 PowerShell propagates nonzero exit', () => assert.match(script, /\$LASTEXITCODE -ne 0/));
test('M129 contains no direct input injection calls', () => assert.doesNotMatch(app, /SendInput\s*\(|DllImport|mouse_event\s*\(/));
